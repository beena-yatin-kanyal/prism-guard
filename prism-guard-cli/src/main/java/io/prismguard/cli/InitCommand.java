package io.prismguard.cli;

import org.fusesource.jansi.Ansi;
import org.springframework.stereotype.Component;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;
import picocli.CommandLine.Parameters;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Sub-command that scaffolds a {@code prismguard.yml} configuration file in the target project.
 * Prints a helpful message and the next steps after creating the file.
 */
@Component
@Command(
    name = "init",
    description = "Create a prismguard.yml configuration file in the specified project directory",
    mixinStandardHelpOptions = true
)
public class InitCommand implements Runnable {

    @Parameters(
        index = "0",
        description = "Project root directory where prismguard.yml will be created (default: current directory)",
        defaultValue = "."
    )
    private Path projectPath;

    @Option(
        names = {"--force"},
        description = "Overwrite an existing prismguard.yml if one already exists"
    )
    private boolean force;

    @Option(
        names = {"--java-version"},
        description = "Java language version to set in the generated config (default: 21)",
        defaultValue = "21"
    )
    private String javaVersion;

    // ── Template content ─────────────────────────────────────────────────────

    private static final String DEFAULT_CONFIG = """
            # ============================================================
            # prismguard.yml — Prism Guard Configuration
            # Generated by: prism-guard init
            # ============================================================

            # Directories (relative to project root) that contain Java source files.
            sourceDirectories:
              - src/main/java

            # Glob patterns to exclude from analysis.
            excludePatterns:
              - "**/*Test.java"
              - "**/*Tests.java"
              - "**/*IT.java"
              - "**/generated/**"
              - "**/target/**"

            # Number of parallel analysis threads. 0 = auto (uses available CPU cores).
            parallelism: 0

            # Java language version used to parse source files.
            # Accepted values: 8, 11, 14, 15, 16, 17, 18, 19, 20, 21
            # Defaults to 21 if omitted. Set this to match your project's java.version in pom.xml.
            javaVersion: %s

            # Report format: html
            outputFormat: html

            # Directory where reports are written (relative to project root).
            outputDirectory: prismguard-reports

            # Exit with code 1 if any CRITICAL findings are produced.
            failOnCritical: false

            # Exit with code 1 if the overall score drops below this value (0 = disabled).
            failOnScoreBelow: 0

            # Rule IDs to disable entirely.
            # disabledRules:
            #   - JAVA009

            # Override the default severity of specific rules.
            # ruleSeverityOverrides:
            #   JAVA002: HIGH
            #   SPRING003: CRITICAL

            # Restrict analysis to these categories only (omit to run all).
            # enabledCategories:
            #   - JAVA_QUALITY
            #   - SPRING_BOOT
            #   - SECURITY

            # ==========================================================
            # Rules — each entry wires a rule ID to an analyzer type.
            # Omit a field to use the analyzer's built-in default.
            # ==========================================================
            rules:

              JAVA002:
                analyzer: long-method
                title: "Long Method"
                severity: MEDIUM
                category: JAVA_QUALITY
                enabled: true
                parameters:
                  maxLines: 50

              JAVA003:
                analyzer: high-cyclomatic-complexity
                title: "High Cyclomatic Complexity"
                severity: HIGH
                category: JAVA_QUALITY
                enabled: true
                parameters:
                  maxComplexity: 10

              JAVA004:
                analyzer: empty-exception-handling
                title: "Swallowed Exception"
                severity: HIGH
                category: JAVA_QUALITY
                enabled: true

              JAVA010:
                analyzer: god-class
                title: "God Class"
                severity: HIGH
                category: JAVA_QUALITY
                enabled: true
                parameters:
                  maxPublicMethods: 20
                  maxLines: 500

              SPRING001:
                analyzer: field-injection
                title: "Field Injection Detected"
                severity: HIGH
                category: DEPENDENCY_INJECTION
                enabled: true

              SPRING003:
                analyzer: controller-business-logic
                title: "Business Logic in Controller"
                severity: HIGH
                category: ARCHITECTURE
                enabled: true
                parameters:
                  maxMethodLines: 30

              SPRING010:
                analyzer: hardcoded-credentials
                title: "Hardcoded Credentials"
                severity: CRITICAL
                category: SECURITY
                enabled: true

              ARCH002:
                analyzer: circular-dependency
                title: "Circular Dependency"
                severity: CRITICAL
                category: ARCHITECTURE
                enabled: true

              ARCH004:
                analyzer: presentation-layer-returning-domain
                title: "Domain Entity Leaked to Presentation Layer"
                severity: HIGH
                category: CLEAN_ARCHITECTURE
                enabled: true

              JPA001:
                analyzer: entity-missing-generated-value
                title: "Entity Missing @GeneratedValue"
                severity: HIGH
                category: JPA_HIBERNATE
                enabled: true

              JPA002:
                analyzer: entity-missing-equals-hashcode
                title: "Entity Missing equals/hashCode"
                severity: HIGH
                category: JPA_HIBERNATE
                enabled: true

              JPA004:
                analyzer: transactional-on-entity
                title: "@Transactional on Entity"
                severity: HIGH
                category: TRANSACTION
                enabled: true

              JPA006:
                analyzer: one-to-many-without-batch-size
                title: "Collection Without Batch-Fetch Strategy"
                severity: MEDIUM
                category: PERFORMANCE
                enabled: true
            """;

    // ── Runnable ─────────────────────────────────────────────────────────────

    @Override
    public void run() {
        Path resolvedProject = projectPath.toAbsolutePath().normalize();

        if (!Files.isDirectory(resolvedProject)) {
            System.err.println(Ansi.ansi()
                .fgRed().a("Error: ").reset()
                .a("Directory not found: " + resolvedProject));
            return;
        }

        Path configPath = resolvedProject.resolve("prismguard.yml");

        if (Files.exists(configPath) && !force) {
            System.out.println(Ansi.ansi()
                .fgYellow().a("prismguard.yml already exists at: ").reset()
                .a(configPath.toString()));
            System.out.println("  Use " + Ansi.ansi().bold().a("--force").reset() + " to overwrite.");
            return;
        }

        try {
            Files.writeString(configPath, DEFAULT_CONFIG.formatted(javaVersion));
            System.out.println(
                Ansi.ansi().fgGreen().bold().a("✓").reset()
                    .a(" Created prismguard.yml in ")
                    .bold().a(resolvedProject.toString()).reset());
            System.out.println(
                Ansi.ansi().a("  Java version : ").fgCyan().bold().a(javaVersion).reset());
            System.out.println();
            System.out.println("  Next steps:");
            System.out.println("  1. Edit " + Ansi.ansi().fgCyan().a("prismguard.yml").reset() +
                " to adjust rules and thresholds.");
            System.out.println("  2. Run " + Ansi.ansi().fgCyan().a("prism-guard analyze").reset() +
                " to start analysis.");
            System.out.println("  3. Run " + Ansi.ansi().fgCyan().a("prism-guard analyze --format=html").reset() +
                " for an interactive dashboard.");
        } catch (IOException e) {
            System.err.println(Ansi.ansi()
                .fgRed().a("Error: Failed to write prismguard.yml: ").reset()
                .a(e.getMessage()));
        }
    }
}
